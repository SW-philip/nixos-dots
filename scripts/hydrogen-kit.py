#!/usr/bin/env python3
"""Build a Hydrogen drumkit from folders of .wav files.

  hydrogen-kit.py [-n NAME] [DIR ...]

Defaults: NAME=sfx, DIRs = assets/sounds + ~/Projects/sound-lab/saved. Installs to
~/.hydrogen/data/drumkits/NAME/; restart Hydrogen (or reopen the Sound Library) to see it.
Each .wav becomes one instrument row, in alphabetical order, MIDI notes from 36.
"""
import argparse
import shutil
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent

INSTRUMENT = """  <instrument>
   <id>{id}</id>
   <name>{name}</name>
   <volume>1</volume>
   <isMuted>false</isMuted>
   <isSoloed>false</isSoloed>
   <pan>0</pan>
   <pitchOffset>0</pitchOffset>
   <randomPitchFactor>0</randomPitchFactor>
   <gain>1</gain>
   <applyVelocity>true</applyVelocity>
   <filterActive>false</filterActive>
   <filterCutoff>1</filterCutoff>
   <filterResonance>0</filterResonance>
   <Attack>0</Attack>
   <Decay>0</Decay>
   <Sustain>1</Sustain>
   <Release>1000</Release>
   <muteGroup>-1</muteGroup>
   <midiOutChannel>-1</midiOutChannel>
   <midiOutNote>{note}</midiOutNote>
   <isStopNote>false</isStopNote>
   <sampleSelectionAlgo>VELOCITY</sampleSelectionAlgo>
   <isHihat>-1</isHihat>
   <lower_cc>0</lower_cc>
   <higher_cc>127</higher_cc>
   <FX1Level>0</FX1Level>
   <FX2Level>0</FX2Level>
   <FX3Level>0</FX3Level>
   <FX4Level>0</FX4Level>
   <instrumentComponent>
    <component_id>0</component_id>
    <gain>1</gain>
    <layer>
     <filename>{file}</filename>
     <min>0</min>
     <max>1</max>
     <gain>1</gain>
     <pitch>0</pitch>
    </layer>
   </instrumentComponent>
  </instrument>
"""

HEAD = """<?xml version="1.0" encoding="UTF-8"?>
<drumkit_info xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns="http://www.hydrogen-music.org/drumkit">
 <name>{name}</name>
 <author>Phil</author>
 <info>Generated by hydrogen-kit.py</info>
 <license>undefined license</license>
 <image></image>
 <imageLicense>undefined license</imageLicense>
 <componentList>
  <drumkitComponent>
   <id>0</id>
   <name>Main</name>
   <volume>1</volume>
  </drumkitComponent>
 </componentList>
 <instrumentList>
"""

TAIL = " </instrumentList>\n</drumkit_info>\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dirs", nargs="*")
    ap.add_argument("-n", "--name", default="sfx")
    a = ap.parse_args()
    dirs = [Path(d).expanduser() for d in a.dirs] or [ROOT / "assets" / "sounds", Path.home() / "Projects/sound-lab/saved"]
    wavs = {}
    for d in dirs:
        for w in sorted(d.glob("*.wav")):
            wavs[w.stem] = w  # a later dir wins on a name clash
    if not wavs:
        raise SystemExit(f"hydrogen-kit: no .wav files in {', '.join(map(str, dirs))}")
    out = Path.home() / ".hydrogen/data/drumkits" / a.name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    xml = HEAD.format(name=escape(a.name))
    for i, (stem, w) in enumerate(sorted(wavs.items())):
        shutil.copy(w, out / w.name)
        xml += INSTRUMENT.format(id=i, name=escape(stem), note=36 + i, file=escape(w.name))
    (out / "drumkit.xml").write_text(xml + TAIL)
    print(f"{len(wavs)} instruments -> {out}")


if __name__ == "__main__":
    main()
